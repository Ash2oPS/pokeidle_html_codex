const DEFAULT_TYPE = "normal";

function freezeRgb(rgb) {
  return Object.freeze([
    Math.max(0, Math.min(255, Number(rgb?.[0]) || 0)),
    Math.max(0, Math.min(255, Number(rgb?.[1]) || 0)),
    Math.max(0, Math.min(255, Number(rgb?.[2]) || 0)),
  ]);
}

function createTypeVfxDescriptor(config = {}) {
  return Object.freeze({
    type: String(config.type || DEFAULT_TYPE),
    projectileKind: String(config.projectileKind || "neutral_orb"),
    projectileScale: Math.max(0.4, Number(config.projectileScale) || 1),
    projectileVariantCount: Math.max(1, Math.round(Number(config.projectileVariantCount) || 1)),
    trailMode: String(config.trailMode || "streak"),
    trailStampKind: String(config.trailStampKind || config.projectileKind || "neutral_orb"),
    trailSpacingPx: Math.max(2, Number(config.trailSpacingPx) || 8),
    trailRadiusMul: Math.max(0.2, Number(config.trailRadiusMul) || 1),
    trailStretch: Math.max(0.5, Number(config.trailStretch) || 1),
    trailAlphaBase: Math.max(0, Math.min(1, Number(config.trailAlphaBase) || 0.12)),
    trailAlphaLife: Math.max(0, Math.min(1, Number(config.trailAlphaLife) || 0.24)),
    trailAccentMix: Math.max(0, Math.min(1, Number(config.trailAccentMix) || 0.5)),
    accent: freezeRgb(config.accent || [232, 240, 255]),
    highlight: freezeRgb(config.highlight || [255, 255, 255]),
    glow: freezeRgb(config.glow || config.accent || [232, 240, 255]),
    laserPattern: String(config.laserPattern || "impulse"),
    beamPattern: String(config.beamPattern || "neutral_band"),
    particleShape: String(config.particleShape || "orb"),
    waveDistanceRatio: Math.max(0, Number(config.waveDistanceRatio) || 0.014),
    waveAmplitudeMin: Math.max(0, Number(config.waveAmplitudeMin) || 1.2),
    waveAmplitudeMax: Math.max(0.1, Number(config.waveAmplitudeMax) || 10),
    waveAmplitudeMul: Math.max(0, Number(config.waveAmplitudeMul) || 1),
    waveFrequency: Math.max(0.1, Number(config.waveFrequency) || 1.2),
    secondaryWave: Math.max(0, Number(config.secondaryWave) || 0.32),
    waveSpeed: Math.max(0.0001, Number(config.waveSpeed) || 0.011),
    particleSpeed: Math.max(0.00001, Number(config.particleSpeed) || 0.00052),
    particleSize: Math.max(0.2, Number(config.particleSize) || 1),
    ribbonAlpha: Math.max(0, Math.min(1, Number(config.ribbonAlpha) || 0.18)),
    ribbonOffset: Math.max(0, Number(config.ribbonOffset) || 3.2),
    ribbonDrift: Math.max(0, Number(config.ribbonDrift) || 0.85),
    jaggedness: Math.max(0, Number(config.jaggedness) || 0),
    widthBoost: Math.max(0.4, Number(config.widthBoost) || 1),
    coreBoost: Math.max(0, Number(config.coreBoost) || 0),
    sourceGlowBoost: Math.max(0.2, Number(config.sourceGlowBoost) || 1),
    impactGlowBoost: Math.max(0.2, Number(config.impactGlowBoost) || 1),
    emitterSpin: Math.max(0, Number(config.emitterSpin) || 0.002),
    impactRingAlpha: Math.max(0, Math.min(1, Number(config.impactRingAlpha) || 0.24)),
    impactRayCount: Math.max(0, Math.round(Number(config.impactRayCount) || 4)),
  });
}

