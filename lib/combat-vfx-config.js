export function normalizeCombatVfxType(typeName) {
  const normalized = String(typeName || DEFAULT_TYPE).toLowerCase().trim();
  return TYPE_VFX_DESCRIPTOR_BY_TYPE[normalized] ? normalized : DEFAULT_TYPE;
}

export function getCombatVfxDescriptor(typeName) {
  return TYPE_VFX_DESCRIPTOR_BY_TYPE[normalizeCombatVfxType(typeName)];
}

export function getProjectileTypeVfxProfile(typeName) {
  const descriptor = getCombatVfxDescriptor(typeName);
  return Object.freeze({
    type: descriptor.type,
    projectileKind: descriptor.projectileKind,
    projectileScale: descriptor.projectileScale,
    projectileVariantCount: descriptor.projectileVariantCount,
    accent: descriptor.accent,
    highlight: descriptor.highlight,
    glow: descriptor.glow,
  });
}

