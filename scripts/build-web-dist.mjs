import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { POKEIDLE_APP_VERSION } from "../version.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, "..");
const DIST_DIR = path.join(ROOT_DIR, "dist");
const SERVICE_WORKER_FILE_NAME = "service-worker.js";
const OFFLINE_SHELL_MANIFEST_FILE_NAME = "offline-shell-manifest.json";
const CACHE_PREFIX = "pokeidle";

export const WEB_BUNDLE_ROOT_FILES = Object.freeze([
  "index.html",
  "game.js",
  "game-runtime.js",
  "styles.css",
  "version.js",
  "game-design-config.js",
  "maintenance-config.js",
]);

export const WEB_BUNDLE_DIRECTORY_NAMES = Object.freeze([
  "vendor",
  "lib",
  "core",
  "systems",
  "domain",
  "infra",
  "assets",
  "map_data",
  "pokemon_data",
  "item_data",
]);

const OFFLINE_SHELL_ROOT_FILES = Object.freeze([
  "index.html",
  "game.js",
  "game-runtime.js",
  "styles.css",
  "version.js",
  "game-design-config.js",
]);

const OFFLINE_SHELL_DIRECTORY_NAMES = Object.freeze([
  "vendor",
  "lib",
  "core",
  "systems",
  "domain",
  "infra",
]);

const OFFLINE_SHELL_FILE_EXTENSIONS = new Set([
  ".js",
  ".mjs",
  ".css",
  ".html",
]);

const EXTRA_OFFLINE_SHELL_FILES = Object.freeze([
  "assets/icons/pokeball-dock.png",
]);

function toPosixPath(filePath) {
  return String(filePath || "").replace(/\\/g, "/");
}

function toRelativeUrl(relativePath) {
  if (!relativePath) {
    return "./";
  }
  return `./${toPosixPath(relativePath)}`;
}

async function listFilesRecursive(rootDir, directoryName) {
  const absoluteDirectoryPath = path.join(rootDir, directoryName);
  const entries = await fs.readdir(absoluteDirectoryPath, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativeEntryPath = path.join(directoryName, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listFilesRecursive(rootDir, relativeEntryPath));
      continue;
    }
    files.push(relativeEntryPath);
  }
  return files;
}

export async function collectOfflineShellUrls(rootDir = ROOT_DIR) {
  const relativePaths = new Set([
    "",
    ...OFFLINE_SHELL_ROOT_FILES,
    ...EXTRA_OFFLINE_SHELL_FILES,
  ]);
  for (const directoryName of OFFLINE_SHELL_DIRECTORY_NAMES) {
    const files = await listFilesRecursive(rootDir, directoryName);
    for (const relativePath of files) {
      const extension = path.extname(relativePath).toLowerCase();
      if (!OFFLINE_SHELL_FILE_EXTENSIONS.has(extension)) {
        continue;
      }
      relativePaths.add(relativePath);
    }
  }
  return Array.from(relativePaths.values())
    .map((relativePath) => toRelativeUrl(relativePath))
    .sort((left, right) => left.localeCompare(right));
}

export function createOfflineShellManifest({
  appVersion = POKEIDLE_APP_VERSION,
  shellUrls = [],
  cachePrefix = CACHE_PREFIX,
} = {}) {
  const version = String(appVersion || "").trim();
  const normalizedShellUrls = Array.from(new Set(
    (Array.isArray(shellUrls) ? shellUrls : []).map((url) => String(url || "").trim()).filter(Boolean),
  )).sort((left, right) => left.localeCompare(right));
  return Object.freeze({
    generatedBy: "npm run web:build",
    version,
    cachePrefix,
    shellCacheName: `${cachePrefix}-shell-v${version}`,
    runtimeCacheName: `${cachePrefix}-runtime-v${version}`,
    serviceWorkerFileName: SERVICE_WORKER_FILE_NAME,
    shellUrls: normalizedShellUrls,
  });
}

export function createServiceWorkerSource(manifest) {
  const shellUrls = JSON.stringify(Array.isArray(manifest?.shellUrls) ? manifest.shellUrls : [], null, 2);
  const shellCacheName = JSON.stringify(String(manifest?.shellCacheName || ""));
  const runtimeCacheName = JSON.stringify(String(manifest?.runtimeCacheName || ""));
  const cachePrefix = JSON.stringify(String(manifest?.cachePrefix || CACHE_PREFIX));
  return `/* Generated by npm run web:build. Do not edit manually. */
const CACHE_PREFIX = ${cachePrefix};
const SHELL_CACHE_NAME = ${shellCacheName};
const RUNTIME_CACHE_NAME = ${runtimeCacheName};
const SHELL_URLS = ${shellUrls};
const SAME_ORIGIN_STATIC_DESTINATIONS = new Set(["script", "style", "image", "font", "audio", "video", "manifest", "worker"]);

function isBypassedRequest(requestUrl, request) {
  if (!request || request.method !== "GET") {
    return true;
  }
  if (requestUrl.origin !== self.location.origin) {
    return true;
  }
  if (String(request.cache || "").toLowerCase() === "no-store") {
    return true;
  }
  return requestUrl.pathname.endsWith("/maintenance-config.js");
}

function isNavigationRequest(request) {
  return request.mode === "navigate";
}

function isSameOriginStaticRequest(requestUrl, request) {
  if (requestUrl.origin !== self.location.origin) {
    return false;
  }
  if (isNavigationRequest(request)) {
    return false;
  }
  if (SAME_ORIGIN_STATIC_DESTINATIONS.has(String(request.destination || "").toLowerCase())) {
    return true;
  }
  const extension = requestUrl.pathname.split(".").pop()?.toLowerCase() || "";
  return ["js", "mjs", "css", "json", "csv", "png", "jpg", "jpeg", "gif", "svg", "ico", "webp", "wav", "mp3", "ogg"].includes(extension);
}

async function purgeLegacyCaches() {
  const cacheNames = await caches.keys();
  await Promise.all(
    cacheNames
      .filter((cacheName) => cacheName.startsWith(CACHE_PREFIX) && cacheName !== SHELL_CACHE_NAME && cacheName !== RUNTIME_CACHE_NAME)
      .map((cacheName) => caches.delete(cacheName)),
  );
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const shellCache = await caches.open(SHELL_CACHE_NAME);
    await shellCache.addAll(SHELL_URLS);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    await purgeLegacyCaches();
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const requestUrl = new URL(request.url);
  if (isBypassedRequest(requestUrl, request)) {
    return;
  }

  if (isNavigationRequest(request)) {
    event.respondWith((async () => {
      const shellCache = await caches.open(SHELL_CACHE_NAME);
      try {
        const networkResponse = await fetch(request);
        if (networkResponse && networkResponse.ok) {
          await shellCache.put(request, networkResponse.clone());
        }
        return networkResponse;
      } catch {
        const cachedResponse = await shellCache.match(request);
        if (cachedResponse) {
          return cachedResponse;
        }
        const cachedIndex = await shellCache.match("./index.html");
        if (cachedIndex) {
          return cachedIndex;
        }
        throw new Error("Offline shell unavailable.");
      }
    })());
    return;
  }

  if (!isSameOriginStaticRequest(requestUrl, request)) {
    return;
  }

  event.respondWith((async () => {
    const runtimeCache = await caches.open(RUNTIME_CACHE_NAME);
    const cachedResponse = await runtimeCache.match(request);
    if (cachedResponse) {
      return cachedResponse;
    }
    const networkResponse = await fetch(request);
    if (networkResponse && networkResponse.ok) {
      await runtimeCache.put(request, networkResponse.clone());
    }
    return networkResponse;
  })());
});
`;
}

async function copyBundleSourceToDist(rootDir, distDir) {
  await fs.rm(distDir, { recursive: true, force: true });
  await fs.mkdir(distDir, { recursive: true });

  for (const fileName of WEB_BUNDLE_ROOT_FILES) {
    await fs.copyFile(path.join(rootDir, fileName), path.join(distDir, fileName));
  }
  for (const directoryName of WEB_BUNDLE_DIRECTORY_NAMES) {
    await fs.cp(path.join(rootDir, directoryName), path.join(distDir, directoryName), {
      recursive: true,
      force: true,
    });
  }
}

async function writeOfflineArtifacts(rootDir, distDir, manifest, serviceWorkerSource) {
  const manifestSource = `${JSON.stringify(manifest, null, 2)}\n`;
  await fs.writeFile(path.join(rootDir, OFFLINE_SHELL_MANIFEST_FILE_NAME), manifestSource, "utf8");
  await fs.writeFile(path.join(rootDir, SERVICE_WORKER_FILE_NAME), serviceWorkerSource, "utf8");
  await fs.writeFile(path.join(distDir, OFFLINE_SHELL_MANIFEST_FILE_NAME), manifestSource, "utf8");
  await fs.writeFile(path.join(distDir, SERVICE_WORKER_FILE_NAME), serviceWorkerSource, "utf8");
}

export async function buildWebBundle({
  rootDir = ROOT_DIR,
  distDir = DIST_DIR,
  appVersion = POKEIDLE_APP_VERSION,
} = {}) {
  await copyBundleSourceToDist(rootDir, distDir);
  const shellUrls = await collectOfflineShellUrls(rootDir);
  const manifest = createOfflineShellManifest({
    appVersion,
    shellUrls,
  });
  const serviceWorkerSource = createServiceWorkerSource(manifest);
  await writeOfflineArtifacts(rootDir, distDir, manifest, serviceWorkerSource);
  return {
    distDir,
    manifest,
  };
}

const isDirectExecution = process.argv[1]
  && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirectExecution) {
  buildWebBundle()
    .then(({ distDir, manifest }) => {
      console.log(`[web:build] Bundle genere dans ${distDir}`);
      console.log(`[web:build] Shell offline ${manifest.shellUrls.length} fichiers, version ${manifest.version}`);
    })
    .catch((error) => {
      console.error("[web:build] Echec de generation du bundle web.", error);
      process.exitCode = 1;
    });
}
