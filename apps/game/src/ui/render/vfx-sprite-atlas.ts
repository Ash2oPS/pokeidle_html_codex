const atlasCache = new Map<string, HTMLCanvasElement>();

function paintMask(
  context: CanvasRenderingContext2D,
  mask: string[],
  primaryColor: string,
  secondaryColor: string,
) {
  for (let rowIndex = 0; rowIndex < mask.length; rowIndex += 1) {
    const row = mask[rowIndex] ?? "";

    for (let columnIndex = 0; columnIndex < row.length; columnIndex += 1) {
      const cell = row[columnIndex];

      if (cell === "0") {
        continue;
      }

      context.fillStyle = cell === "1" ? primaryColor : secondaryColor;
      context.fillRect(columnIndex, rowIndex, 1, 1);
    }
  }
}

export function getVfxSprite(
  spriteId: VfxSpriteId,
  primaryColor: string,
  secondaryColor: string,
): HTMLCanvasElement | null {
  if (typeof document === "undefined") {
    return null;
  }

  const cacheKey = `${spriteId}:${primaryColor}:${secondaryColor}`;
  const cached = atlasCache.get(cacheKey);

  if (cached) {
    return cached;
  }

  const mask = spriteMasks[spriteId];
  const canvas = document.createElement("canvas");
  canvas.width = 16;
  canvas.height = 16;
  const context = canvas.getContext("2d");

  if (!context) {
    return null;
  }

  context.imageSmoothingEnabled = false;
  paintMask(context, mask, primaryColor, secondaryColor);
  atlasCache.set(cacheKey, canvas);
  return canvas;
}
